/** Simple in-memory sliding window. Sufficient for a single Node instance; swap for a shared store if scaled out. */
const hits = new Map<string, number[]>();

export function allowSubmission(key: string, limit = 5, windowMs = 10 * 60 * 1000) {
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((time) => now - time < windowMs);
  if (recent.length >= limit) {
    hits.set(key, recent);
    return false;
  }
  recent.push(now);
  hits.set(key, recent);
  if (hits.size > 5000) hits.clear();
  return true;
}
